export function mapFormToArea(form: string, lineKey: string): WorkpaperAreaId {
  if (lineKey.startsWith('SchCA540NR') || lineKey.startsWith('F540NR') || lineKey.startsWith('ScheduleS') || lineKey.startsWith('FTB')) {
    return 'california';
  }
  if (lineKey === 'Sch1.16' || lineKey === 'Sch1.17' || lineKey === 'Sch1.13' || form === 'F8606' || form === 'F8889' || form === 'F8938') {
    return 'retirement_and_foreign';
  }
  if (form === 'F7203' || lineKey.startsWith('SchE.28') || lineKey === 'SchE.32') {
    return 'pass_throughs_and_basis';
  }
  if (form === 'SchE' || form === 'F4562-E' || form === 'F4797' || form === 'F8582') {
    return 'rentals_and_sale';
  }
  if (form === 'SchC' || form === 'F4562-C' || form === 'SchSE' || form === 'F8995' || lineKey === 'Sch1.3' || lineKey === 'Sch1.15') {
    return 'business';
  }
  if (form === 'SchB' || form === 'SchD' || form === 'F8949' || form === 'F8960') {
    return 'investments_and_digital_assets';
  }
  if (form === 'SchA' || form === 'F8283' || form === 'F8812' || form === 'F8863' || form === 'F2441' || form === 'F8867' || form === 'Sch3') {
    return 'deductions_and_credits';
  }
  if (form === 'F6251' || form === 'F8959' || lineKey.startsWith('F1040.1')) {
    return 'wages_and_stock_compensation';
  }
  if (form === 'F2210' || lineKey.startsWith('F1040.25') || lineKey.startsWith('F1040.26') || lineKey.startsWith('F1040.3')) {
    return 'payments_and_filing';
  }
  return 'intake_and_engagement';
}

